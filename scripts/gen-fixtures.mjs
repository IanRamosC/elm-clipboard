// Generates tests/ProtocolFixtures.elm from fixtures/protocol.json, so the
// Elm tests check the same JSON as the TypeScript tests in js/test.
// Run: node scripts/gen-fixtures.mjs
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const fixtures = JSON.parse(readFileSync(new URL("fixtures/protocol.json", root), "utf8"));

const elmString = (value) => JSON.stringify(JSON.stringify(value));
const section = (name, entries) =>
  [
    `${name} : List ( String, String )`,
    `${name} =`,
    ...Object.entries(entries).map(
      ([key, value], i) => `    ${i === 0 ? "[" : ","} ( ${JSON.stringify(key)}, ${elmString(value)} )`,
    ),
    "    ]",
  ].join("\n");

const out = `module ProtocolFixtures exposing (fixture, replies, requests)

-- GENERATED by scripts/gen-fixtures.mjs from fixtures/protocol.json. Do not edit.


${section("requests", fixtures.requests)}


${section("replies", fixtures.replies)}


fixture : String -> List ( String, String ) -> String
fixture key list =
    list
        |> List.filter (\\( k, _ ) -> k == key)
        |> List.head
        |> Maybe.map Tuple.second
        |> Maybe.withDefault ("missing fixture " ++ key)
`;
writeFileSync(new URL("tests/ProtocolFixtures.elm", root), out);
console.log("wrote tests/ProtocolFixtures.elm");
